import os
import sys
from datetime import datetime, timezone
import pandas as pd

# Allow importing dataset_loader from parent directory
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
from dataset_loader import DATASET_NAME, get_dataset

def main():
    print(f"[*] Setting up Feast Feature Store for dataset: '{DATASET_NAME}'...")
    df, raw_feature_cols, target_col = get_dataset()

    # 1. Select two numeric columns to compute engineered features
    numeric_cols = [c for c in df.select_dtypes(include=["number"]).columns if c != target_col]
    valid_cols = [c for c in numeric_cols if df[c].std() > 1e-6]
    if len(valid_cols) < 2:
        valid_cols = numeric_cols[:2]

    col_a = valid_cols[0]
    col_b = valid_cols[1] if len(valid_cols) > 1 else valid_cols[0]
    print(f"  Selected features for interaction: '{col_a}' and '{col_b}'")

    # 2. Compute 2 engineered features
    df["feat_interaction_prod"] = (df[col_a] * df[col_b]).astype(float)
    df["feat_interaction_ratio"] = (df[col_a] / (df[col_b].abs() + 1e-5)).astype(float)
    engineered_cols = ["feat_interaction_prod", "feat_interaction_ratio"]

    # 3. Add primary entity key: sample_id (int64)
    df["sample_id"] = range(len(df))
    df["sample_id"] = df["sample_id"].astype("int64")

    # 4. Add Feast timestamp columns (UTC)
    now_utc = datetime.now(timezone.utc)
    df["event_timestamp"] = pd.to_datetime(now_utc)
    df["created_timestamp"] = pd.to_datetime(now_utc)

    # Ensure all raw feature columns are float64 for schema consistency
    for c in raw_feature_cols:
        df[c] = df[c].astype(float)

    # 5. Save Parquet offline store
    data_dir = os.path.join(os.path.dirname(__file__), "data")
    os.makedirs(data_dir, exist_ok=True)
    parquet_path = os.path.join(data_dir, "features.parquet")
    df.to_parquet(parquet_path, index=False)
    print(f"[OK] Features exported to Parquet: {parquet_path} ({len(df)} rows)")

    # 6. Dynamically generate features.py
    features_py_content = f'''# Dynamically generated by setup_feature_store.py for dataset '{DATASET_NAME}'
from datetime import timedelta
from feast import Entity, FeatureService, FeatureView, Field, FileSource
from feast.types import Float64
from feast.value_type import ValueType

# Define Entity
sample_id = Entity(
    name="sample_id",
    join_keys=["sample_id"],
    value_type=ValueType.INT64,
    description="Sample unique integer identifier",
)

# Define Offline Source
source = FileSource(
    name="features_parquet_source",
    path="data/features.parquet",
    timestamp_field="event_timestamp",
    created_timestamp_column="created_timestamp",
)

# Raw Features View
raw_features_fv = FeatureView(
    name="raw_features_fv",
    entities=[sample_id],
    ttl=timedelta(days=365),
    schema=[
{chr(10).join(f'        Field(name="{col}", dtype=Float64),' for col in raw_feature_cols)}
    ],
    source=source,
)

# Engineered Features View
engineered_features_fv = FeatureView(
    name="engineered_features_fv",
    entities=[sample_id],
    ttl=timedelta(days=365),
    schema=[
        Field(name="feat_interaction_prod", dtype=Float64),
        Field(name="feat_interaction_ratio", dtype=Float64),
    ],
    source=source,
)

# Unified Feature Service
exam_feature_service = FeatureService(
    name="exam_feature_service",
    features=[raw_features_fv, engineered_features_fv],
)
'''

    features_py_path = os.path.join(os.path.dirname(__file__), "features.py")
    with open(features_py_path, "w", encoding="utf-8") as f:
        f.write(features_py_content)

    print(f"[OK] Dynamic Feast definitions written to: {features_py_path}")
    print(f"[SUCCESS] Feature store setup completed successfully.")

if __name__ == "__main__":
    main()
