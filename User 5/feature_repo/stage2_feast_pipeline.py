import os
import sys
import subprocess
from datetime import datetime, timezone, timedelta
import pandas as pd
from feast import FeatureStore

def main():
    repo_dir = os.path.dirname(os.path.abspath(__file__))
    input_parquet = os.path.abspath(os.path.join(repo_dir, "..", "data", "processed", "validated_features.parquet"))
    output_training_parquet = os.path.abspath(os.path.join(repo_dir, "..", "data", "processed", "feast_training_set.parquet"))

    if not os.path.exists(input_parquet):
        print(f"[ERROR] Stage 1 input '{input_parquet}' not found!", file=sys.stderr)
        sys.exit(1)

    print(f"[*] [Stage 2] Loading validated features from: {input_parquet}...")
    df = pd.read_parquet(input_parquet)

    # 1. Copy data into feature_repo/data/features.parquet for Feast FileSource
    data_dir = os.path.join(repo_dir, "data")
    os.makedirs(data_dir, exist_ok=True)
    feast_source_parquet = os.path.join(data_dir, "features.parquet")
    df.to_parquet(feast_source_parquet, index=False)
    print(f"  [OK] Feast source parquet written: {feast_source_parquet}")

    # 2. Extract feature column names
    meta_cols = ["sample_id", "target_label", "event_timestamp", "created_timestamp", "feat_interaction_prod", "feat_interaction_ratio"]
    raw_feature_cols = [c for c in df.columns if c not in meta_cols]

    # 3. Dynamically generate features.py
    features_py_content = f'''# Dynamically generated by stage2_feast_pipeline.py
from datetime import timedelta
from feast import Entity, FeatureService, FeatureView, Field, FileSource
from feast.types import Float64
from feast.value_type import ValueType

sample_id = Entity(
    name="sample_id",
    join_keys=["sample_id"],
    value_type=ValueType.INT64,
    description="Sample ID",
)

source = FileSource(
    name="e2e_features_source",
    path="data/features.parquet",
    timestamp_field="event_timestamp",
    created_timestamp_column="created_timestamp",
)

raw_features_fv = FeatureView(
    name="raw_features_fv",
    entities=[sample_id],
    ttl=timedelta(days=365),
    schema=[
{chr(10).join(f'        Field(name="{col}", dtype=Float64),' for col in raw_feature_cols)}
    ],
    source=source,
)

engineered_features_fv = FeatureView(
    name="engineered_features_fv",
    entities=[sample_id],
    ttl=timedelta(days=365),
    schema=[
        Field(name="feat_interaction_prod", dtype=Float64),
        Field(name="feat_interaction_ratio", dtype=Float64),
    ],
    source=source,
)

e2e_feature_service = FeatureService(
    name="e2e_feature_service",
    features=[raw_features_fv, engineered_features_fv],
)
'''

    features_py_path = os.path.join(repo_dir, "features.py")
    with open(features_py_path, "w", encoding="utf-8") as f:
        f.write(features_py_content)
    print(f"  [OK] Generated {features_py_path}")

    # 4. Register definitions into Feast Registry via feast apply
    print("[*] Running 'feast apply'...")
    feast_bin = os.path.join(os.path.dirname(sys.executable), "feast.exe")
    apply_cmd = [feast_bin, "apply"] if os.path.exists(feast_bin) else ["feast", "apply"]
    subprocess.run(apply_cmd, cwd=repo_dir, check=True)

    # 5. Materialize features into SQLite Online Store
    now_utc = datetime.now(timezone.utc)
    start_date = now_utc - timedelta(days=365)
    print(f"[*] Materializing features into SQLite online store up to {now_utc.isoformat()}...")
    store = FeatureStore(repo_path=repo_dir)
    store.materialize(start_date=start_date, end_date=now_utc)
    print(f"  [OK] Online store materialized at: {os.path.join(data_dir, 'online_store.db')}")

    # 6. Retrieve Point-in-Time Correct Historical Dataset for Training
    print("[*] Retrieving historical features for Stage 3 model training...")
    entity_df = df[["sample_id", "event_timestamp", "target_label"]].copy()

    feature_service = store.get_feature_service("e2e_feature_service")
    training_data = store.get_historical_features(
        entity_df=entity_df,
        features=feature_service,
    ).to_df()

    # Save training dataset
    training_data.to_parquet(output_training_parquet, index=False)
    print(f"[SUCCESS] Stage 2 complete. Exported training set: {output_training_parquet}")
    print(f"  Training set shape: {training_data.shape}")

if __name__ == "__main__":
    main()
